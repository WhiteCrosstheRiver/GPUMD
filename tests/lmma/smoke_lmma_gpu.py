"""Small GPU integration checks for opt-in LM-MA-ES, not a timing benchmark.

Requires Python 3, NumPy, nvidia-smi, and a free NVIDIA GPU. A synthetic Si/Ge
fixture is generated by default; --train and --test may supply small Si/Ge
extended-XYZ files instead. All artifacts stay in a new --output directory.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess

import numpy as np


DIMENSION = 18
NEURONS = 8
NETWORK_PARAMETERS = (DIMENSION + 2) * NEURONS
SHARED_BIAS = 2 * NETWORK_PARAMETERS
PARAMETERS = SHARED_BIAS + 1 + 2 * 4 * 3 * 5
BASE_CONFIG = (
    "type 2 Si Ge\nversion 4\ncutoff 4 4\nn_max 2 2\nbasis_size 4 4\n"
    "l_max 4 2 0\nneuron 8\nbatch 1000 0\npopulation 10\n"
    "generation 100\nlambda_e 1\nlambda_f 1\nlambda_v 0.1\n"
)


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def require_free_gpu(gpu):
    result = subprocess.run(
        ["nvidia-smi", "-i", str(gpu), "--query-compute-apps=pid",
         "--format=csv,noheader,nounits"],
        text=True, capture_output=True, check=True,
    )
    lines = [line.strip() for line in result.stdout.splitlines() if line.strip()]
    require(not any(line.isdigit() for line in lines),
            f"GPU {gpu} is occupied; no test will launch: {lines}")
    require(all("No running processes" in line for line in lines),
            f"Unexpected nvidia-smi output: {lines}")


def synthetic_xyz():
    # Distorted eight-atom cells exercise both species and nonzero angular terms.
    # Reference labels are artificial; this checks integration, not model quality.
    corners = np.array([[x, y, z] for x in (0., 2.5)
                        for y in (0., 2.5) for z in (0., 2.5)])
    rng = np.random.default_rng(42016)
    frames = []
    for frame in range(4):
        positions = corners + 2.0 + rng.normal(0., .04, corners.shape)
        lines = ["8", 'Lattice="9 0 0 0 9 0 0 0 9" '
                 'Properties=species:S:1:pos:R:3:force:R:3 '
                 f'energy={-24.0 + .01 * frame:.8f} '
                 'virial="0 0 0 0 0 0 0 0 0" pbc="T T T"']
        for atom, xyz in enumerate(positions):
            species = "Si" if atom % 2 == 0 else "Ge"
            lines.append(f"{species} " + " ".join(f"{v:.10f}" for v in xyz)
                         + " 0 0 0")
        frames.append("\n".join(lines) + "\n")
    return "".join(frames)


def read_loss(folder):
    values = np.loadtxt(folder / "loss.out", ndmin=2)
    require(values.shape == (1, 10), f"Unexpected loss dimensions: {values.shape}")
    require(np.isfinite(values).all(), "Non-finite reported loss")
    require(int(values[0, 0]) == 100, "Missing generation-100 report")
    return values[0]


def read_parameters(path):
    lines = path.read_text().splitlines()
    require(lines[0].split() == ["nep4", "2", "Si", "Ge"],
            "Unexpected model element order/version")
    end = next(i for i, line in enumerate(lines) if line.startswith("ANN ")) + 1
    values = np.array([float(line) for line in lines[end:]])
    require(len(values) == PARAMETERS + DIMENSION, "Unexpected model length")
    require(np.isfinite(values).all(), "Non-finite exported model")
    return values[:PARAMETERS]


def run_case(args, name, mean, sigma, *, optimizer="lmma", seed="42016",
             regularization=(0., 0.), binary=None, config=BASE_CONFIG,
             expect_error=None):
    require_free_gpu(args.gpu)
    folder = args.output / name
    folder.mkdir()
    for filename, source in (("train.xyz", args.train), ("test.xyz", args.test)):
        if source:
            shutil.copyfile(source, folder / filename)
        else:
            (folder / filename).write_text(synthetic_xyz(), encoding="ascii")
    np.savetxt(folder / "nep.restart", np.column_stack((mean, sigma)), fmt="%.9e")
    initial_hash = sha256(folder / "nep.restart")
    (folder / "nep.in").write_text(
        config + f"lambda_1 {regularization[0]}\nlambda_2 {regularization[1]}\n",
        encoding="ascii",
    )
    env = os.environ.copy()
    env["CUDA_VISIBLE_DEVICES"] = str(args.gpu)
    for key in ("GPUMD_EXPERIMENT_OPTIMIZER", "GPUMD_EXPERIMENT_SEED"):
        env.pop(key, None)
    if optimizer is not None:
        env["GPUMD_EXPERIMENT_OPTIMIZER"] = optimizer
    if seed is not None:
        env["GPUMD_EXPERIMENT_SEED"] = seed
    with (folder / "run.log").open("w") as log:
        result = subprocess.run([str(binary or args.binary)], cwd=folder, env=env,
                                stdout=log, stderr=subprocess.STDOUT,
                                timeout=args.timeout)
    log = (folder / "run.log").read_text(errors="replace")
    if expect_error:
        require(result.returncode != 0, f"{name}: invalid input was accepted")
        require(expect_error in log, f"{name}: unexpected failure; inspect {folder / 'run.log'}")
        return {"status": "PASS", "expected_error": expect_error}
    require(result.returncode == 0, f"{name}: failed; inspect {folder / 'run.log'}")
    row = read_loss(folder)
    if optimizer == "lmma":
        require("Experimental LM-MA-ES: global ranking;" in log,
                "Requested experimental optimizer was not selected")
        require(sha256(folder / "nep.restart") == initial_hash,
                "LMMA overwrote the native initial restart")
        checkpoint = (folder / "nep.restart.lmma").read_text()
        require(checkpoint.startswith("experimental_lmma_checkpoint 1\n"),
                "Missing LMMA state format tag")
        require("\niteration 99\n" in checkpoint,
                "Generation-zero calibration was incorrectly counted as an LMMA update")
        require("rng_mt19937_64 " in checkpoint and "normal_distribution " in checkpoint,
                "LMMA checkpoint omitted random state")
    else:
        require("Experimental LM-MA-ES:" not in log, "SNES unexpectedly selected LMMA")
    return {"status": "PASS", "loss": row.tolist(), "model_sha256": sha256(folder / "nep.txt")}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, required=True)
    parser.add_argument("--baseline", type=Path,
                        help="Optional original nep executable for exact default-SNES parity")
    parser.add_argument("--output", type=Path, required=True,
                        help="New directory; existing paths are rejected")
    parser.add_argument("--gpu", default="0", help="Free NVIDIA GPU index or UUID")
    parser.add_argument("--train", type=Path, help="Optional small Si/Ge training XYZ")
    parser.add_argument("--test", type=Path, help="Optional small Si/Ge validation XYZ")
    parser.add_argument("--timeout", type=float, default=180.)
    args = parser.parse_args()
    if args.timeout <= 0:
        parser.error("--timeout must be positive")
    for field in ("binary", "baseline", "train", "test"):
        value = getattr(args, field)
        if value:
            value = value.resolve()
            if not value.is_file():
                parser.error(f"Missing {field}: {value}")
            setattr(args, field, value)
    require_free_gpu(args.gpu)
    args.output = args.output.resolve()
    args.output.mkdir(parents=True, exist_ok=False)
    report = {"status": "running", "binary_sha256": sha256(args.binary),
              "gpu": args.gpu, "tests": {}}
    rng = np.random.default_rng(42016)
    mean = rng.normal(0., .1, PARAMETERS)
    sigma = np.full(PARAMETERS, .02)
    try:
        regularization = (.3, .2)
        tested = run_case(args, "lmma_regularization", mean, sigma,
                          regularization=regularization)
        parameters = read_parameters(args.output / "lmma_regularization/nep.txt")
        # Native NEP4's global regularizer excludes the shared output bias,
        # but divides by all parameters. report_error only adjusts that bias.
        selected = np.delete(parameters, SHARED_BIAS)
        expected = np.array([regularization[0] * np.abs(selected).sum() / PARAMETERS,
                             regularization[1] * np.sqrt((selected @ selected) / PARAMETERS)])
        actual = np.array(tested["loss"])[2:4]
        np.testing.assert_allclose(actual, expected, rtol=2e-4, atol=6e-6,
                                   err_msg="GPU L1/L2 do not match independent parameter norms")
        tested["independent_l1_l2"] = expected.tolist()
        report["tests"]["lmma_regularization"] = tested

        report["tests"]["default_unset"] = run_case(
            args, "default_unset", mean, sigma, optimizer=None, seed=None)
        report["tests"]["explicit_snes"] = run_case(
            args, "explicit_snes", mean, sigma, optimizer="snes", seed=None)
        for filename in ("loss.out", "nep.txt", "nep.restart"):
            require((args.output / "default_unset" / filename).read_bytes()
                    == (args.output / "explicit_snes" / filename).read_bytes(),
                    f"Unset/explicit SNES mismatch: {filename}")
        if args.baseline:
            report["baseline_sha256"] = sha256(args.baseline)
            report["tests"]["baseline"] = run_case(
                args, "baseline", mean, sigma, optimizer=None, seed=None, binary=args.baseline)
            for filename in ("loss.out", "nep.txt", "nep.restart"):
                require((args.output / "default_unset" / filename).read_bytes()
                        == (args.output / "baseline" / filename).read_bytes(),
                        f"Original/default SNES mismatch: {filename}")
        else:
            report["tests"]["baseline"] = {"status": "SKIPPED", "reason": "--baseline not supplied"}

        cases = [
            ("unknown_optimizer", {"optimizer": "invalid"}, "Unknown GPUMD_EXPERIMENT_OPTIMIZER"),
            ("missing_seed", {"seed": None}, "requires GPUMD_EXPERIMENT_SEED"),
            ("negative_seed", {"seed": "-1"}, "decimal digits only"),
            ("whitespace_seed", {"seed": " 1"}, "decimal digits only"),
            ("overflow_seed", {"seed": "18446744073709551616"}, "outside the uint64 range"),
            ("unsupported_nep3", {"config": BASE_CONFIG.replace("version 4", "version 3")},
             "requires ordinary NEP4 training"),
        ]
        for name, changes, message in cases:
            report["tests"][name] = run_case(args, name, mean, sigma,
                                             expect_error=message, **changes)
        anisotropic = sigma.copy()
        anisotropic[0] *= 2
        report["tests"]["anisotropic_sigma"] = run_case(
            args, "anisotropic_sigma", mean, anisotropic,
            expect_error="finite mean and isotropic initial sigma")
        invalid_mean = mean.copy()
        invalid_mean[0] = np.nan
        report["tests"]["nonfinite_mean"] = run_case(
            args, "nonfinite_mean", invalid_mean, sigma,
            expect_error="finite mean and isotropic initial sigma")
        report["status"] = "PASS"
    except Exception as error:
        report.update(status="FAIL", error=repr(error))
        raise
    finally:
        (args.output / "verification.json").write_text(
            json.dumps(report, indent=2, allow_nan=False) + "\n", encoding="ascii")
    print(json.dumps(report, indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
